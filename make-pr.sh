#!/usr/bin/env bash
# optio-agent-kit make-pr — put the guides on a new branch of an Optio checkout, commit, and export patches.
#
#   ./make-pr.sh [--layer core|all] [--branch NAME] [--out DIR] <optio-checkout>
#
#   --layer core   upstream pull request: only the generic guides (default)
#   --layer all    merge request into our fork: core + airgap layer
#   --branch NAME  default: docs/agent-guides (core) or docs/agent-guides-airgap (all)
#   --out DIR      where to write the patch series (default: <checkout>/../optio-agent-guides-patches)
#   --no-verify    skip the repo's git hooks (only when node_modules isn't installed; CI will still check)
#
# Needs a clean working tree. Creates the branch from the current HEAD, installs, commits, writes
# `git format-patch` files you can carry anywhere (a removable drive, a merge request, an upstream PR). Never pushes.
set -euo pipefail

KIT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KIT_VERSION="$(cat "$KIT/VERSION")"

layer=core branch="" out="" target="" verify=""
while [ $# -gt 0 ]; do
  case "$1" in
    --layer) layer="${2:?}"; shift ;;
    --branch) branch="${2:?}"; shift ;;
    --out) out="${2:?}"; shift ;;
    --no-verify) verify="--no-verify" ;;
    -h|--help) sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    -*) echo "unknown option: $1" >&2; exit 2 ;;
    *) target="$1" ;;
  esac
  shift
done
case "$layer" in core|all) ;; *) echo "--layer must be core or all" >&2; exit 2 ;; esac
[ -n "$target" ] || { echo "usage: ./make-pr.sh [--layer core|all] [--branch NAME] [--out DIR] <optio-checkout>" >&2; exit 2; }
target="$(cd "$target" && pwd)"
[ -n "$branch" ] || { [ "$layer" = core ] && branch="docs/agent-guides" || branch="docs/agent-guides-airgap"; }
[ -n "$out" ] || out="$(dirname "$target")/optio-agent-guides-patches"

if [ -n "$(git -C "$target" status --porcelain --untracked-files=no)" ]; then
  echo "$target has uncommitted changes; commit or stash them first" >&2; exit 2
fi
base="$(git -C "$target" rev-parse HEAD)"
git -C "$target" switch -c "$branch"

"$KIT/install.sh" --layer "$layer" --no-check "$target"
(cd "$target" && bash scripts/check-agent-guides.sh) || { echo "guide check failed; branch $branch left for inspection" >&2; exit 1; }

git -C "$target" add -A -- AGENTS.md docs/agent-guides scripts/check-agent-guides.sh scripts/helm-value-map.sh helm/VALUES-MAP.md \
  $(cd "$target" && git ls-files --others --modified --exclude-standard -- '*AGENTS.md' '*CLAUDE.md')
if [ "$layer" = all ]; then
  git -C "$target" add -A -- CLAUDE.md MANIFEST.md .agent-guides .gitignore .claude docs/airgap scripts/airgap
fi

if [ "$layer" = core ]; then
  subject="docs(agents): add area guides with main ideas for coding agents"
  body="Adds a short AGENTS.md to each main area (apps/api, its services, apps/web, apps/cli, every package,
helm, images, scripts): what the area is, its main ideas, a file map and how to change it safely. Each folder
also gets a CLAUDE.md that imports its AGENTS.md, following the root convention. helm/VALUES-MAP.md
(generated by scripts/helm-value-map.sh) maps every Helm value to its template, env var and the code that
reads it. docs/agent-guides/README.md explains Optio's main ideas in one page and indexes the guides; the
root AGENTS.md gains a short \"Start here\" section. scripts/check-agent-guides.sh fails when a guide
names a file that no longer exists or the value map is out of date.

Motivation: smaller and faster models lose their way in the 67 KB root AGENTS.md; scoped guides load only
when an agent works in that folder.

Generated with optio-agent-kit $KIT_VERSION."
else
  subject="docs(agents): add agent guides and air-gap layer (optio-agent-kit $KIT_VERSION)"
  body="Core guides (nested AGENTS.md with each area's main ideas) plus the air-gapped fork layer: root
CLAUDE.md router, docs/airgap (what we do, gotchas, team-owned site facts and worklog), Claude Code
skills and scout agent, scripts/airgap/impact.sh."
fi
git -C "$target" commit -q $verify -m "$subject" -m "$body"

mkdir -p "$out"
git -C "$target" format-patch -q -o "$out" "$base..$branch"
echo
echo "Branch $branch created in $target (base ${base:0:8})."
echo "Patches: $out"
ls "$out"
[ "$layer" = core ] && echo "Pull request text: $KIT/PR_DESCRIPTION.md"
echo "Apply elsewhere with: git am $out/*.patch"
